def random_ua() -> str:
    """返回一个随机 User-Agent 字符串。"""
    return random.choice(_USER_AGENTS)


def get_headers(referer: Optional[str] = None) -> dict[str, str]:
    """构建带随机 UA 和可选 Referer 的请求头。

    每次调用返回不同的 UA，模拟不同浏览器访问。
    """
    ua = random_ua()
    headers = {
        "User-Agent": ua,
        "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,image/webp,*/*;q=0.8",
        "Accept-Language": "zh-CN,zh;q=0.9,en;q=0.8",
        # 不发送 Accept-Encoding，urlopen 不会自动解压 gzip
        "Cache-Control": "max-age=0",
        "Connection": "keep-alive",
    }
    if referer:
        headers["Referer"] = referer
    return headers


def random_delay(min_sec: float = 0.3, max_sec: float = 1.2):
    """随机休眠，模拟人类浏览节奏。"""
    time.sleep(random.uniform(min_sec, max_sec))
